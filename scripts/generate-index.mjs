#!/usr/bin/env node
// Generates INDEX.md — the canonical content inventory. Never hand-edit INDEX.md; re-run this.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const topicDirs = readdirSync(ROOT)
  .filter((d) => /^\d{2}-/.test(d) && statSync(join(ROOT, d)).isDirectory())
  .sort();

const countQuestions = (file) =>
  (readFileSync(file, 'utf8').match(/^## Question \d+/gm) || []).length;

const mdFilesIn = (dir) => {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...mdFilesIn(p));
    else if (entry.name.endsWith('.md')) out.push(p);
  }
  return out;
};

let totalFiles = 0;
let totalQuestions = 0;
const rows = topicDirs.map((dir) => {
  const files = mdFilesIn(join(ROOT, dir)).filter((f) => !f.endsWith('README.md'));
  const questions = files.reduce((n, f) => n + countQuestions(f), 0);
  totalFiles += files.length;
  totalQuestions += questions;
  return { dir, files: files.length, questions };
});

const table = rows
  .map((r) => `| [${r.dir}](./${r.dir}/) | ${r.files} | ${r.questions} |`)
  .join('\n');

writeFileSync(
  join(ROOT, 'INDEX.md'),
  `# Content Inventory

> Auto-generated by \`scripts/generate-index.mjs\` — do not edit by hand.

| Topic | Files | Q&A |
|-------|-------|-----|
${table}
| **Total** | **${totalFiles}** | **${totalQuestions}** |
`,
);
console.log(`INDEX.md written: ${totalFiles} content files, ${totalQuestions} questions across ${topicDirs.length} topics`);
rows.forEach((r) => console.log(`  ${r.dir}: ${r.files} files, ${r.questions} Q&A`));
